#!/usr/bin/env python3
"""The border of the safety region Noord- en Oost-Gelderland (VNOG), from the CBS area divisions at PDOK (open data).
Result: worker/src/veiligheidsregio.js and website/assets/veiligheidsregio.json: { naam, bron, ringen: [[[lat, lon], ...]] },
thinned to a few hundred points so the map layer stays light."""
import json, pathlib, urllib.parse, urllib.request

UA = {"User-Agent": "A-Alerts/2.0 (+https://a-alerts.nl)", "Accept": "application/json"}
NAAM = "Noord- en Oost-Gelderland"

def wfs(jaar, laag):
    url = f"https://service.pdok.nl/cbs/gebiedsindelingen/{jaar}/wfs/v1_0?" + urllib.parse.urlencode({
        "request": "GetFeature", "service": "WFS", "version": "2.0.0", "typeName": f"gebiedsindelingen:{laag}",
        "outputFormat": "application/json", "srsName": "EPSG:4326"})
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return json.load(r)

feature, bron = None, None
for jaar in (2026, 2025, 2024, 2023):
    for laag in ("veiligheidsregio_gegeneraliseerd", "veiligheidsregio_niet_gedetailleerd", "veiligheidsregio_labelpoint"):
        if "labelpoint" in laag: continue
        try:
            fc = wfs(jaar, laag)
        except Exception as e:  # noqa: BLE001
            print("niet:", jaar, laag, e); continue
        for f in fc.get("features", []):
            if NAAM.lower() in json.dumps(f.get("properties", {}), ensure_ascii=False).lower():
                feature, bron = f, f"CBS gebiedsindelingen {jaar} (PDOK)"; break
        if feature: break
    if feature: break
if not feature:
    raise SystemExit("Veiligheidsregio niet gevonden bij PDOK")

def dp(pts, eps):
    """Douglas-Peucker on [lon, lat] points."""
    if len(pts) < 3: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]; dx, dy = bx - ax, by - ay; n = (dx * dx + dy * dy) ** 0.5 or 1e-12
        best, bi = 0.0, None
        for i in range(a + 1, b):
            d = abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / n
            if d > best: best, bi = d, i
        if bi is not None and best > eps:
            keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

g = feature["geometry"]
polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
# Flip axis order when the service answers lat,lon (the Netherlands: lat ≈ 52, lon ≈ 6).
def lonlat(p): return (p[0], p[1]) if p[0] < 20 else (p[1], p[0])
ringen = []
for poly in polys:
    buiten = [lonlat(p) for p in poly[0]]
    if len(buiten) < 20: continue  # tiny islands
    dun = dp(buiten, 0.0008)
    ringen.append([[round(lat, 5), round(lon, 5)] for lon, lat in dun])
uit = {"naam": NAAM, "bron": bron, "ringen": ringen}
print(bron, [len(r) for r in ringen])
tekst = json.dumps(uit, ensure_ascii=False, separators=(",", ":"))
root = pathlib.Path(__file__).resolve().parents[2]
(root / "website/assets/veiligheidsregio.json").write_text(tekst, encoding="utf-8")
(root / "worker/src/veiligheidsregio.js").write_text("// Generated by tools/geodata/fetch_veiligheidsregio.py: the border of the safety region (CBS, via PDOK). [lat, lon]\nexport default " + tekst + ";\n", encoding="utf-8")
